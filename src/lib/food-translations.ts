export function translateFoodName(name: string | null | undefined, locale: "fa" | "en"): string {
  if (!name) return locale === "fa" ? "نامشخص" : "Unknown";
  if (locale === "en") return name;
  // Check for bilingual format "English|||Persian"
  if (name.includes("|||")) {
    const parts = name.split("|||");
    return parts[1] || parts[0];
  }
  if (FOOD_NAME_TRANSLATIONS[name]) return FOOD_NAME_TRANSLATIONS[name];
  const lower = name.toLowerCase();
  for (const [en, fa] of Object.entries(FOOD_NAME_TRANSLATIONS)) {
    if (en.toLowerCase() === lower) return fa;
  }
  if (/[\u0600-\u06FF]/.test(name)) return name;
  return name;
}

export function translateMacroLabel(label: string, locale: "fa" | "en"): string {
  if (locale === "en") return label;
  const map: Record<string, string> = {
    "Calories": "کالری", "Protein": "پروتئین", "Carbs": "کربوهیدرات",
    "Fats": "چربی", "Fat": "چربی", "Water": "آب", "cal": "کالری", "kcal": "کیلوکالری",
  };
  return map[label] ?? label;
}
